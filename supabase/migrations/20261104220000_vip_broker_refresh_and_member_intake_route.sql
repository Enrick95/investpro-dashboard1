-- Add current VIP affiliation brokers while retaining Vantage for existing records.
begin;
set local lock_timeout = '3s';
set local statement_timeout = '20s';

alter table public.vip_invitations drop constraint vip_invitation_broker_known;
alter table public.vip_invitations add constraint vip_invitation_broker_known check (
  affiliation_broker is null or affiliation_broker in ('raise_fx', 'vantage', 'vtmarkets', 'puprime', 'axi', 'bullwaves')
);
alter table public.vip_memberships drop constraint vip_membership_broker_known;
alter table public.vip_memberships add constraint vip_membership_broker_known check (
  affiliation_broker is null or affiliation_broker in ('raise_fx', 'vantage', 'vtmarkets', 'puprime', 'axi', 'bullwaves')
);
alter table public.vip_access_requests drop constraint vip_access_requests_affiliation_broker_check;
alter table public.vip_access_requests add constraint vip_access_requests_affiliation_broker_check check (
  affiliation_broker is null or affiliation_broker in ('raise_fx', 'vantage', 'vtmarkets', 'puprime', 'axi', 'bullwaves')
);
alter table public.vip_access_requests drop constraint vip_access_requests_verified_affiliation_broker_check;
alter table public.vip_access_requests add constraint vip_access_requests_verified_affiliation_broker_check check (
  verified_affiliation_broker is null or verified_affiliation_broker in ('raise_fx', 'vantage', 'vtmarkets', 'puprime', 'axi', 'bullwaves')
);

-- Update the existing service-only broker allowlists without changing RPC signatures or grants.
do $$
declare
  v_sig regprocedure;
  v_definition text;
  v_old constant text := '''raise_fx'', ''vantage'', ''puprime'', ''axi''';
  v_new constant text := '''raise_fx'', ''vantage'', ''vtmarkets'', ''puprime'', ''axi'', ''bullwaves''';
begin
  foreach v_sig in array array[
    'public.vip_update_identity(uuid,text,text,text)'::regprocedure,
    'public.vip_review_access_request_checked(uuid,text,uuid,text,text,text,text,date,numeric,boolean,boolean)'::regprocedure
  ] loop
    v_definition := pg_get_functiondef(v_sig);
    if position(v_old in v_definition) = 0 then
      raise exception 'Expected VIP broker allowlist not found in %', v_sig;
    end if;
    execute replace(v_definition, v_old, v_new);
  end loop;
end;
$$;

-- Keep new broker labels in staff activity generated by the database trigger.
do $$
declare
  v_definition text;
  v_old constant text := 'when ''raise_fx'' then ''Raise FX'' when ''vantage'' then ''Vantage''
      when ''puprime'' then ''PU Prime'' when ''axi'' then ''Axi''';
  v_new constant text := 'when ''raise_fx'' then ''Raise FX'' when ''vantage'' then ''Vantage''
      when ''vtmarkets'' then ''VT Markets'' when ''puprime'' then ''PU Prime''
      when ''axi'' then ''Axi'' when ''bullwaves'' then ''Bullwaves''';
begin
  v_definition := pg_get_functiondef('public.vip_capture_admin_activity()'::regprocedure);
  if position(v_old in v_definition) = 0 then raise exception 'Expected VIP activity labels not found'; end if;
  execute replace(v_definition, v_old, v_new);
end;
$$;

-- Existing members now complete follow-up requests on the archived intake URL.
alter table public.vip_request_completion_events drop constraint vip_request_completion_events_href_check;
alter table public.vip_request_completion_events add constraint vip_request_completion_events_href_check
  check (href in ('/vip/deja-membre', '/vip/deja-membre-original', '/vip/rejoindre'));
do $$
declare
  v_definition text;
  v_old constant text := 'else ''/vip/deja-membre'' end';
  v_new constant text := 'else ''/vip/deja-membre-original'' end';
begin
  v_definition := pg_get_functiondef('public.vip_request_completion_action(uuid,integer,uuid,text[],text)'::regprocedure);
  if position(v_old in v_definition) = 0 then raise exception 'Expected existing-member notification route not found'; end if;
  execute replace(v_definition, v_old, v_new);
end;
$$;

notify pgrst, 'reload schema';
commit;
